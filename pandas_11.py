orders = pd.DataFrame({
    'restaurant': ['Spice Hub', 'Spice Hub', 'Spice Hub',
                   'Pizza Point', 'Pizza Point', 'Pizza Point',
                   'Burger House', 'Burger House'],
    'month': ['January', 'January', 'February',
              'January', 'February', 'February',
              'January', 'February'],
    'total_amount': [300, 500, 400, 250, 350, 450, 200, 300]
})

result = pd.pivot_table(
    orders,
    index='restaurant',
    columns='month',
    values='total_amount',
    aggfunc='mean'
)

print(result)

jan = pd.DataFrame({
    'Product': ['T-Shirt', 'Jeans', 'Shoes'],
    'Sales': [5000, 8000, 12000]
})
jan.to_csv('sales_jan.csv', index=False)

feb = pd.DataFrame({
    'Product': ['T-Shirt', 'Jeans', 'Shoes'],
    'Sales': [6000, 7000, 10000]
})
feb.to_csv('sales_feb.csv', index=False)

mar = pd.DataFrame({
    'Product': ['T-Shirt', 'Jeans', 'Shoes'],
    'Sales': [7000, 9000, 15000]
})
mar.to_csv('sales_mar.csv', index=False)

jan_data = pd.read_csv('sales_jan.csv')
feb_data = pd.read_csv('sales_feb.csv')
mar_data = pd.read_csv('sales_mar.csv')

all_sales = pd.concat(
    [jan_data, feb_data, mar_data],
    ignore_index=True
)

print("All Monthly Sales:")
print(all_sales)
total_sales = all_sales.groupby('Product')['Sales'].sum()

print("\nTotal Sales Per Product:")
print(total_sales)